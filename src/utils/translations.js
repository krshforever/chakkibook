function getNestedValue(obj, path) {
  if (!obj) return undefined;
  const keys = path.split('.');
  let current = obj;
  for (const k of keys) {
    if (current && typeof current === 'object' && k in current) {
      current = current[k];
    } else {
      return undefined;
    }
  }
  return current;
}

export function t(key, lang = 'hinglish') {
  const currentLang = lang || 'hinglish';
  
  // 1. Try current language
  let val = getNestedValue(translations[currentLang], key);
  if (val !== undefined) return val;

  // 2. Fallback to hinglish
  if (currentLang !== 'hinglish') {
    val = getNestedValue(translations.hinglish, key);
    if (val !== undefined) return val;
  }

  // 3. Fallback to en
  if (currentLang !== 'en') {
    val = getNestedValue(translations.en, key);
    if (val !== undefined) return val;
  }

  // 4. Return last key or original path as safety net
  const parts = key.split('.');
  return parts[parts.length - 1] || key;
}

export function useTranslation() {
  const language = useStore((state) => state.language || 'hinglish');
  return {
    t: (key) => t(key, language),
    language
  };
}
